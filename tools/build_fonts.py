#!/usr/bin/env python3
"""Rasterize the interface and catalog glyphs at their screen sizes."""

import argparse
import json
import unicodedata
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
STYLES = (
    ("Compact", "Regular", 18, 18, 15, 18),
    ("Body", "Bold", 20, 28, 23, 32),
    ("Heading", "Bold", 29, 28, 26, 32),
)


def rasterize(font, char):
    left, top, right, bottom = font.getbbox(char, anchor="ls")
    advance = max(round(font.getlength(char)), right)
    if right <= left or bottom <= top:
        return (advance, 0, 0, 0, 0), b""
    image = Image.new("L", (right - left, bottom - top))
    ImageDraw.Draw(image).text((-left, -top), char, font=font, anchor="ls", fill=255)
    bounds = image.getbbox()
    if bounds is None:
        return (advance, 0, 0, 0, 0), b""
    bitmap = image.crop(bounds)
    left += bounds[0]
    top += bounds[1]
    coverage = [(value + 8) // 17 for value in bitmap.tobytes()]
    if len(coverage) % 2:
        coverage.append(0)
    packed = bytes(high << 4 | low for high, low in zip(coverage[::2], coverage[1::2]))
    return (advance, bitmap.width, bitmap.height, left, top), packed


def build(fonts, output):
    catalog = json.loads((ROOT / "asset-pack/item-names.json").read_text())
    characters = {chr(code) for code in range(32, 127)}
    characters.update("".join(label for _, label in catalog["languages"]))
    for item in catalog["items"]:
        characters.update("".join(item["names"]))
    header = [
        "// Generated by tools/build_fonts.py.",
        "// Atkinson Hyperlegible, Noto Sans CJK TC, and Noto Emoji, SIL Open Font License 1.1.",
        "#pragma once",
        "#include <stdint.h>",
        "namespace uifont {",
        "struct Glyph {",
        "    uint32_t code, offset;",
        "    uint8_t advance, width, height;",
        "    int8_t left, top;",
        "};",
        "struct Face {",
        "    const Glyph* glyphs;",
        "    const uint8_t* coverage;",
        "    unsigned count;",
        "    int baseline, height;",
        "};",
    ]
    coverage = bytearray()
    offsets = {}
    faces = []
    for style, weight, latin_size, cjk_size, baseline, height in STYLES:
        latin = ImageFont.truetype(fonts / f"AtkinsonHyperlegible-{weight}.ttf", latin_size)
        cjk = ImageFont.truetype(fonts / "NotoSansCJKtc-Medium.otf", cjk_size)
        emoji = ImageFont.truetype(fonts / "NotoEmoji-Regular.ttf", cjk_size)
        missing = {font: rasterize(font, "\U0010ffff") for font in (latin, cjk, emoji)}
        glyphs = []
        for char in sorted(characters):
            if char.isascii() or unicodedata.name(char, "").startswith("LATIN "):
                font = latin
            else:
                font = emoji if ord(char) > 0xffff else cjk
            metrics, bitmap = rasterize(font, char)
            if (metrics, bitmap) == missing[font]:
                raise ValueError(f"Missing glyph U+{ord(char):04X}")
            if bitmap not in offsets:
                offsets[bitmap] = len(coverage)
                coverage.extend(bitmap)
            fields = ", ".join(map(str, (offsets[bitmap], *metrics)))
            glyphs.append(f"    {{0x{ord(char):04x}, {fields}}},")
        header.extend([f"static constexpr Glyph {style}Glyphs[] = {{", *glyphs, "};"])
        faces.extend([
            f"static constexpr Face {style} = {{",
            f"    {style}Glyphs, Coverage, {len(glyphs)}, {baseline}, {height}",
            "};",
        ])
    header.append("static constexpr uint8_t Coverage[] = {")
    for start in range(0, len(coverage), 24):
        header.append("    " + ", ".join(f"0x{byte:02x}" for byte in coverage[start:start + 24]) + ",")
    header.extend(["};", *faces, "} // namespace uifont"])
    output.write_text("\n".join(header) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font_directory", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "firmware/generated/ui_fonts.h")
    args = parser.parse_args()
    build(args.font_directory, args.output)
