#!/usr/bin/env python3
"""Generate language labels and catalog-indexed display names for the firmware."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "asset-pack"


def main():
    catalog = json.loads((ASSETS / "catalog.json").read_text())
    data = json.loads((ASSETS / "item-names.json").read_text())
    languages, items = data["languages"], data["items"]
    if languages[0][0] != "en" or len({code for code, _ in languages}) != len(languages):
        raise ValueError("Expected unique languages with English first")
    if [(row["kind"], row["id"]) for row in items] != [(row["kind"], row["id"]) for row in catalog]:
        raise ValueError("Localized names must follow the firmware catalog order")

    quote = lambda label: json.dumps(label, ensure_ascii=False)
    header = [
        "// Generated by tools/build_item_names.py.",
        "#pragma once",
        '#include "catalog.h"',
        "",
        "namespace names {",
        "struct Language { const char* code; const char* label; };",
        "constexpr Language languages[] = {",
        *(f"    {{{quote(code)}, {quote(label)}}}," for code, label in languages),
        "};",
        "constexpr unsigned languageCount = sizeof(languages) / sizeof(languages[0]);",
        "constexpr unsigned english = 0;",
        "constexpr const char* catalogNames[][languageCount] = {",
    ]
    for row in items:
        if len(row["names"]) != len(languages) or any(not name.strip() for name in row["names"]):
            raise ValueError(f"Missing localized name for {row['kind']} {row['id']}")
        header.append("    {" + ", ".join(map(quote, row["names"])) + "},")
    header.extend([
        "};",
        'static_assert(sizeof(catalogNames) / sizeof(catalogNames[0]) == catalogCount, "Name rows must match the catalog");',
        "} // namespace names",
    ])
    (ROOT / "firmware/generated/item_names.h").write_text("\n".join(header) + "\n")


if __name__ == "__main__":
    main()
