#!/usr/bin/env python3
"""Compile the packaged asset index into the standalone firmware."""

import json
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "asset-pack"
KINDS = {"gifts": 0, "lab": 1, "ghosts": 2, "codes": 3, "money": 4}


def main():
    items = json.loads((ASSETS / "catalog.json").read_text())
    records = json.loads((ASSETS / "records.json").read_text())
    pack = (ASSETS / "assets.bin").read_bytes()
    expected = struct.pack("<4sIII", b"KPA1", len(pack), len(records), zlib.crc32(pack[16:]))
    if pack[:16] != expected:
        raise ValueError("Asset header does not match the asset pack and record index")
    if any(not 0 < packed <= 0xffff or not 0 < raw <= 4096 for _, packed, raw, _ in records):
        raise ValueError("Asset block lengths exceed the firmware record format")

    money_index = next(i for i, item in enumerate(items) if item["kind"] == "money")
    header = [
        "// Generated by tools/build_catalog.py.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct AssetRecord { uint32_t offset; uint16_t packed, raw; uint32_t crc; };",
        "struct CatalogItem {",
        "    uint16_t id, image, firstBlock, blocks;",
        "    uint8_t kind, category, field;",
        "    uint32_t size, uid, charUid;",
        "    const char* code;",
        "};",
        "extern const AssetRecord assetRecords[];",
        "extern const CatalogItem catalogItems[];",
        "#ifdef KPA_DEFINE_CATALOG",
        "const AssetRecord assetRecords[] = {",
    ]
    header.extend(f"    {{{offset},{size},{raw},0x{crc:08x}u}}," for offset, size, raw, crc in records)
    header.extend(["};", "const CatalogItem catalogItems[] = {"])
    for item in items:
        fields = [
            *(str(item[key]) for key in ("id", "image", "data", "blocks")),
            str(KINDS[item["kind"]]), *(str(item[key]) for key in ("category", "field", "size")),
            f"0x{item['uid']:08x}u", f"0x{item['char_uid']:08x}u", json.dumps(item["code"]),
        ]
        header.append("    {" + ",".join(fields) + "},")
    header.extend([
        "};",
        "#endif",
        f"constexpr unsigned catalogCount = {len(items)};",
        f"constexpr unsigned moneyItemIndex = {money_index};",
        f"constexpr unsigned neonGiftStart = {money_index + 1};",
        f"constexpr unsigned assetCount = {len(records)};",
        f"constexpr unsigned assetPackBytes = {len(pack)};",
    ])
    (ROOT / "firmware/generated/catalog.h").write_text("\n".join(header) + "\n")


if __name__ == "__main__":
    main()
